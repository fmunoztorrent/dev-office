/**
 * Where emoji stay emoji: what people and agents write and say (a chat, the log, the archive's entries,
 * the whiteboard's post-its, the daily's minutes, an agent's question), and the fields.
 */
export const KEEP = '.talk, .log, #log, .feed-body, .ar-read, .ar-body, .btw-a, .btw-q, .bv-postit, .daily-body li, .pr-q, .inbox-text span, .sheet-history, .sheet-did, .sheet-say, [data-raw], input, textarea, select, option, script, style';

/**
 * A <select> draws its options' text itself, so an emoji there would be the system's. The options keep
 * only their text (each one's icon goes to its data-icon) and, given a `slot` (an element next to the
 * select, styled as .px), it shows the chosen option's icon in pixel art. Call it after filling the
 * select and when its value changes.
 */
export function selectIcons(sel, slot = null) {
  for (const o of sel.options) {
    const { icon, text } = leadingIcon(o.textContent);
    if (icon) { o.dataset.icon = icon; o.textContent = text; }
  }
  if (!slot) return;
  const name = sel.selectedOptions?.[0]?.dataset.icon || '';
  slot.hidden = !name;
  if (!name) return;
  slot.classList.toggle('mono', MONO.has(name));
  slot.style.setProperty('--px', `url("${iconURL(name)}")`);
}

/** Turns the emoji of the interface's texts under `root` into pixel icons (the ones it knows). */
export function pixelize(root) {
  if (!root || typeof document === 'undefined') return 0;
  let n = 0;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue || !/\p{Extended_Pictographic}/u.test(node.nodeValue)) return NodeFilter.FILTER_REJECT;
      const el = node.parentElement;
      if (!el || el.closest(KEEP) || el.closest('.px')) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    // in a drawing (the map, the impact): an SVG text that starts with an icon gets an image before it
    if (node.parentElement instanceof SVGElement) { n += svgIcon(node.parentElement); continue; }
    const text = node.nodeValue;
    const frag = document.createDocumentFragment();
    let last = 0, changed = false;
    for (const m of text.matchAll(EMOJI_RE)) {
      const name = iconOf(m[0]);
      if (!name) continue;
      if (m.index > last) frag.append(text.slice(last, m.index));
      const i = document.createElement('i');
      i.className = MONO.has(name) ? 'px mono' : 'px';
      i.setAttribute('role', 'img');
      i.setAttribute('aria-label', m[0]);
      i.dataset.emoji = m[0];
      i.style.setProperty('--px', `url("${iconURL(name)}")`);
      frag.append(i);
      last = m.index + m[0].length;
      changed = true;
      n++;
    }
    if (!changed) continue;
    if (last < text.length) frag.append(text.slice(last));
    node.replaceWith(frag);
  }
  return n;
}

/** An SVG <text> that starts with an emoji with an icon: the icon as an <image> where the emoji was, the text after it. */
function svgIcon(text) {
  if (text.tagName !== 'text' || text.dataset.px) return 0;
  const { icon, text: rest } = leadingIcon(text.textContent);
  if (!icon || text.getAttribute('text-anchor') === 'middle' || text.getAttribute('text-anchor') === 'end') return 0;
  const size = Math.max(12, Math.round((parseFloat(getComputedStyle(text).fontSize) || 13) / 12) * 12);
  const x = parseFloat(text.getAttribute('x') || '0'), y = parseFloat(text.getAttribute('y') || '0');
  const img = document.createElementNS('http://www.w3.org/2000/svg', 'image');
  img.setAttribute('href', iconURL(icon));
  img.setAttribute('x', String(x));
  img.setAttribute('y', String(y - size * 0.85));
  img.setAttribute('width', String(size));
  img.setAttribute('height', String(size));
  img.setAttribute('class', 'px-svg');
  img.setAttribute('style', 'image-rendering: pixelated');
  text.before(img);
  text.dataset.px = '1';
  text.textContent = rest;
  text.setAttribute('x', String(x + (rest ? size + 4 : 0)));
  return 1;
}

/**
 * Keeps the page's interface in pixel icons: now, and every time something in it changes. It also gives the
 * stylesheet the game's pointers and the checkbox's tick (--cur-arrow, --cur-hand, --px-check).
 */
export function watchPixelIcons(root = document.body) {
  const css = document.documentElement.style;
  css.setProperty('--cur-arrow', `url("data:image/svg+xml;utf8,${encodeURIComponent(iconSVG('cursor', 24))}") 0 0, default`);
  css.setProperty('--cur-hand', `url("data:image/svg+xml;utf8,${encodeURIComponent(iconSVG('grab', 24))}") 7 0, pointer`);
  css.setProperty('--px-check', `url("${iconURL('check')}")`);
  pixelize(root);
  let queued = false;
  const pending = new Set();
  const run = () => { queued = false; for (const el of pending) if (el.isConnected) pixelize(el); pending.clear(); };
  const obs = new MutationObserver((list) => {
    for (const m of list) {
      const el = m.type === 'characterData' ? m.target.parentElement : m.target;
      if (el && !el.closest?.('.px')) pending.add(el);
    }
    if (!queued && pending.size) { queued = true; requestAnimationFrame(run); }
  });
  obs.observe(root, { childList: true, subtree: true, characterData: true });
  return obs;
}
