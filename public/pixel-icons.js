/** An emoji or symbol, as the interface writes it (with or without its variation selector, a skin tone…). */
export const EMOJI_RE = /\p{Extended_Pictographic}(?:️|︎|[\u{1F3FB}-\u{1F3FF}])?(?:‍\p{Extended_Pictographic}️?)*/gu;

/** The icon of an emoji, or null. */
export const iconOf = (emoji) => EMOJI[String(emoji || '').replace(/[︎️\u{1F3FB}-\u{1F3FF}]/gu, '')] || null;

/** An icon as SVG: a rectangle per run of pixels of a color, crisp at any size (`px`: its size, for a cursor). */
export function iconSVG(name, px = null) {
  const rows = ICONS[name];
  if (!rows) return '';
  const paths = {};
  rows.forEach((row, y) => {
    for (let x = 0; x < SIZE;) {
      const ch = row[x];
      if (ch === '.' || ch === ' ' || !PALETTE[ch]) { x++; continue; }
      let w = 1;
      while (row[x + w] === ch) w++;
      (paths[ch] ||= []).push(`M${x} ${y}h${w}v1h-${w}z`);
      x += w;
    }
  });
  const body = Object.entries(paths).map(([ch, d]) => `<path fill="${MONO.has(name) ? '#000' : PALETTE[ch]}" d="${d.join('')}"/>`).join('');
  const size = px ? ` width="${px}" height="${px}"` : '';
  return `<svg xmlns="http://www.w3.org/2000/svg"${size} viewBox="0 0 ${SIZE} ${SIZE}" shape-rendering="crispEdges">${body}</svg>`;
}

const URLS = new Map();
/** An icon as a data: URL (cached). */
export function iconURL(name) {
  if (!URLS.has(name)) URLS.set(name, `data:image/svg+xml;utf8,${encodeURIComponent(iconSVG(name))}`);
  return URLS.get(name);
}

/**
 * Draws an icon on a 2D canvas, a square of `size` pixels at (x, y) (its top-left corner); a mono one in
 * `color`. Pixel by pixel: as crisp as the canvas.
 */
export function drawIcon(ctx, name, x, y, size = SIZE, color = '#f1f3fa') {
  const rows = ICONS[name];
  if (!rows) return false;
  const k = size / SIZE;
  for (let j = 0; j < SIZE; j++) {
    const row = rows[j];
    for (let i = 0; i < SIZE;) {
      const ch = row[i];
      if (ch === '.' || ch === ' ' || !PALETTE[ch]) { i++; continue; }
      let w = 1;
      while (row[i + w] === ch) w++;
      ctx.fillStyle = MONO.has(name) ? color : PALETTE[ch];
      ctx.fillRect(Math.round(x + i * k), Math.round(y + j * k), Math.round((i + w) * k) - Math.round(i * k), Math.round((j + 1) * k) - Math.round(j * k));
      i += w;
    }
  }
  return true;
}

/** Splits a text into its leading icon (if it starts with an emoji that has one) and the rest. */
export function leadingIcon(text) {
  const s = String(text ?? '');
  const m = s.match(/^\s*(\p{Extended_Pictographic}(?:️|︎)?)\s*/u);
  const name = m && iconOf(m[1]);
  return name ? { icon: name, text: s.slice(m[0].length) } : { icon: null, text: s };
}

